"""Write the schema out, and check the written copy is still right.

A schema in a document goes stale the week after it is written. This one is
generated from a book that has just had every migration run on it, so it cannot
disagree with the code, and CI runs it with ``--check`` so that a migration
that changes a table and leaves the document behind fails the build rather than
the next person to read it.
"""

from __future__ import annotations

import sqlite3
import sys
import tempfile
from pathlib import Path

from scowbox.store.book import book
from scowbox.store.migrations import latest
from scowbox.store.sqlite import rows
from scowbox.tools.scan import project_root

NAME = "schema_dump"
DOCUMENT = "docs/schema.md"


def live_schema() -> list[str]:
    """The schema of a book with every migration run on it."""
    with (
        tempfile.TemporaryDirectory() as where,
        book(Path(where) / "schema.sqlite3", create=True) as connection,
    ):
        return _dump(connection)


def _dump(connection: sqlite3.Connection) -> list[str]:
    lines = [
        "# Schema",
        "",
        "Generated by `python -m scowbox.tools.schema_dump`. Do not edit.",
        "",
        f"Schema version {latest()}.",
        "",
    ]
    found = rows(
        connection,
        "SELECT type, name, sql FROM sqlite_master WHERE sql IS NOT NULL ORDER BY type DESC, name",
    )
    for row in found:
        lines.append(f"## {row['name']} ({row['type']})")
        lines.append("")
        lines.append("```sql")
        lines.extend(_tidy(row["sql"]))
        lines.append("```")
        lines.append("")
    return lines


def _tidy(sql: str) -> list[str]:
    """Take the migration's indentation off without changing the statement."""
    lines = [line.rstrip() for line in sql.strip().splitlines()]
    inner = [line for line in lines[1:] if line.strip()]
    pad = min((len(line) - len(line.lstrip()) for line in inner), default=0)
    return [lines[0], *[line[pad:] if line.strip() else line for line in lines[1:]]]


def document_path() -> Path:
    """Where the written schema lives."""
    return project_root() / DOCUMENT


def write() -> Path:
    """Rewrite the document from the live schema."""
    where = document_path()
    where.parent.mkdir(parents=True, exist_ok=True)
    where.write_text("\n".join(live_schema()) + "\n", encoding="utf-8")
    return where


def findings() -> list[str]:
    """Whether the written schema still matches the code."""
    where = document_path()
    if not where.exists():
        return [f"{DOCUMENT} is missing; write it with the tool"]
    wanted = "\n".join(live_schema()) + "\n"
    if where.read_text(encoding="utf-8") != wanted:
        return [f"{DOCUMENT} is out of date; rewrite it with the tool"]
    return []


def main(argv: list[str] | None = None) -> int:
    """Rewrite the document, or check it with ``--check``."""
    args = sys.argv[1:] if argv is None else argv
    if "--check" in args:
        found = findings()
        if found:
            print(f"{NAME}: {found[0]}")
            return 1
        print(f"{NAME}: nothing to report")
        return 0
    print(f"{NAME}: wrote {write()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
