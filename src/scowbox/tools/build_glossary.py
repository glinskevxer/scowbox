"""Write the glossary out, and check the written copy is still right.

Every closed vocabulary in this package is an enum: the three ways a reach is
measured, the eight reasons a dredge stops, the three kinds of ground that take
material. Somebody arriving at this codebase needs that list before they need
anything else, and a list maintained by hand in a document is a list that is
wrong by the second week.

So it is generated from the enums themselves, with each member's value as the
term and the class docstring as the heading. If the vocabulary changes and the
document is not rewritten, CI says so.
"""

from __future__ import annotations

import enum
import importlib
import inspect
import sys
from pathlib import Path

from scowbox.tools.scan import PACKAGE, modules, project_root

NAME = "build_glossary"
DOCUMENT = "docs/glossary.md"
SKIP = ("scowbox.tools.",)


def vocabularies() -> list[tuple[str, type[enum.Enum]]]:
    """Every enum in the package, by the module that defines it."""
    found = []
    for module in modules():
        if module.name.startswith(SKIP):
            continue
        loaded = importlib.import_module(module.name)
        for name, value in vars(loaded).items():
            if not isinstance(value, type) or not issubclass(value, enum.Enum):
                continue
            if value.__module__ != module.name or name.startswith("_"):
                continue
            found.append((module.name, value))
    return sorted(found, key=lambda pair: (pair[0], pair[1].__name__))


def glossary() -> list[str]:
    """The glossary as it should be."""
    lines = [
        "# Glossary",
        "",
        "Generated by `python -m scowbox.tools.build_glossary`. Do not edit.",
        "",
        "Every closed vocabulary in the package, taken from the enums themselves.",
        "",
    ]
    for where, vocabulary in vocabularies():
        lines.append(f"## {vocabulary.__name__}")
        lines.append("")
        lines.append(f"`{where}`")
        lines.append("")
        summary = (inspect.getdoc(vocabulary) or "").strip().splitlines()
        if summary:
            lines.append(summary[0])
            lines.append("")
        for member in vocabulary:
            lines.append(f"- **{member.value}** — `{vocabulary.__name__}.{member.name}`")
        lines.append("")
    return lines


def document_path() -> Path:
    """Where the written glossary lives."""
    return project_root() / DOCUMENT


def write(where: Path | None = None) -> Path:
    """Rewrite the document, somewhere else if the caller says so.

    The override exists for the tests. Checking that a stale document is caught
    means writing a stale one, and doing that in the checkout means two runs of
    the suite at once tread on each other and fail for a reason that has
    nothing to do with either of them.

    Rewrite the document from the enums."""
    where = where or document_path()
    where.parent.mkdir(parents=True, exist_ok=True)
    where.write_text("\n".join(glossary()) + "\n", encoding="utf-8")
    return where


def findings(where: Path | None = None) -> list[str]:
    """Whether the written glossary still matches the code."""
    where = where or document_path()
    if not where.exists():
        return [f"{DOCUMENT} is missing; write it with the tool"]
    if where.read_text(encoding="utf-8") != "\n".join(glossary()) + "\n":
        return [f"{DOCUMENT} is out of date; rewrite it with the tool"]
    return []


def terms() -> list[str]:
    """Every term the glossary defines, for anything that wants the list."""
    return [
        member.value
        for _, vocabulary in vocabularies()
        for member in vocabulary
        if isinstance(member.value, str)
    ]


def main(argv: list[str] | None = None) -> int:
    """Rewrite the document, or check it with ``--check``."""
    args = sys.argv[1:] if argv is None else argv
    if "--check" in args:
        found = findings()
        if found:
            print(f"{NAME}: {found[0]}")
            return 1
        print(f"{NAME}: {len(terms())} terms, nothing to report")
        return 0
    print(f"{NAME}: wrote {write()} with {len(terms())} terms from {PACKAGE}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
