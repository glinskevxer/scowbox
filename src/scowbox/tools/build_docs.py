"""Write the command reference out, and check the written copy is still right.

Same arrangement as the schema: the document is generated from the real command
tree, and CI runs the generator with ``--check`` so that a new command with no
entry, or an entry for a command that has gone, fails the build.

What it cannot check is whether the help text is any good. That is what
``check_help`` is for, and between them a command is documented if and only if
somebody wrote a sentence about it.
"""

from __future__ import annotations

import sys
from pathlib import Path

import click

from scowbox.cli.main import cli
from scowbox.tools.check_help import walk
from scowbox.tools.scan import project_root

NAME = "build_docs"
DOCUMENT = "docs/commands.md"


def reference() -> list[str]:
    """The command reference as it should be."""
    lines = [
        "# Commands",
        "",
        "Generated by `python -m scowbox.tools.build_docs`. Do not edit.",
        "",
    ]
    for path, command in walk(cli):
        if path == "cli":
            continue
        lines.extend(_command(path, command))
    return lines


def _command(path: str, command: click.Command) -> list[str]:
    words = path.replace("cli ", "scowbox ", 1)
    lines = [f"## `{words}`", ""]
    text = (command.help or "").strip().splitlines()
    lines.append(text[0] if text else "")
    lines.append("")
    arguments = [p for p in command.params if isinstance(p, click.Argument)]
    if arguments:
        lines.append("Arguments: " + ", ".join(f"`{p.name}`" for p in arguments))
        lines.append("")
    options = [
        p
        for p in command.params
        if isinstance(p, click.Option) and p.name not in ("help", "version")
    ]
    for option in options:
        flags = ", ".join(f"`{o}`" for o in option.opts)
        lines.append(f"- {flags} — {(option.help or '').strip()}")
    if options:
        lines.append("")
    return lines


def document_path() -> Path:
    """Where the written reference lives."""
    return project_root() / DOCUMENT


def write() -> Path:
    """Rewrite the document from the command tree."""
    where = document_path()
    where.parent.mkdir(parents=True, exist_ok=True)
    where.write_text("\n".join(reference()) + "\n", encoding="utf-8")
    return where


def findings() -> list[str]:
    """Whether the written reference still matches the command tree."""
    where = document_path()
    if not where.exists():
        return [f"{DOCUMENT} is missing; write it with the tool"]
    wanted = "\n".join(reference()) + "\n"
    if where.read_text(encoding="utf-8") != wanted:
        return [f"{DOCUMENT} is out of date; rewrite it with the tool"]
    return []


def main(argv: list[str] | None = None) -> int:
    """Rewrite the document, or check it with ``--check``."""
    args = sys.argv[1:] if argv is None else argv
    if "--check" in args:
        found = findings()
        if found:
            print(f"{NAME}: {found[0]}")
            return 1
        print(f"{NAME}: nothing to report")
        return 0
    print(f"{NAME}: wrote {write()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
